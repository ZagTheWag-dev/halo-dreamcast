#!/usr/bin/env python3
"""Placeholder definitions of the n64.h platform API the Dreamcast layer
does not implement yet (port/dc/src/dc_stubs_generated.c).

    python tools/dc_stubs.py build/dc/halo.elf.log

Reads the undefined references of a failed link (the log of
`ninja -f build/dc/build.ninja`), finds each name's declaration in the N64
layer's headers and the game glue, and writes a weak definition of it: a
function doing nothing (returning zero), or a zeroed variable. A real
definition in port/dc/src replaces the weak one at the link.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "port/dc/src/dc_stubs_generated.c"
SEARCH = [*sorted((ROOT / "port/n64/src").glob("*.h")), *sorted((ROOT / "port/n64/game").glob("*.c")),
          *sorted((ROOT / "port/n64/src").glob("n64_*.c"))]
HEADERS = ["n64.h", "n64_fx_format.h", "n64_sniper_ribbon.h"]


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def flatten(text):
    """top-level statements, one a line (bodies dropped)"""
    out, depth, current = [], 0, []
    for ch in text:
        if ch == "{":
            if depth == 0:
                out.append("".join(current) + "{")
                current = []
            depth += 1
        elif ch == "}":
            depth -= 1
        elif depth == 0:
            if ch == ";":
                out.append("".join(current) + ";")
                current = []
            elif ch == "\n" and "".join(current).lstrip().startswith("#"):
                current = []
            else:
                current.append(ch)
    return [" ".join(s.split()) for s in out]


def declarations():
    found = {}
    for path in SEARCH:
        for statement in flatten(strip_comments(path.read_text(encoding="utf-8", errors="replace"))):
            m = re.match(r"^(?:extern\s+)?(?!return|typedef|static)([\w\s\*]+?)\b(\w+)\s*\((.*)\)\s*(?:__attribute__\(\(.*\)\))?\s*[;{]$",
                         statement)
            if m:
                found.setdefault(m.group(2), ("function", m.group(1).strip(), m.group(3).strip(), path.name))
                continue
            m = re.match(r"^extern\s+([\w\s\*]+?)\b(\w+)\s*((?:\[[^\]]*\])*)\s*;$", statement)
            if m:
                found.setdefault(m.group(2), ("variable", m.group(1).strip(), m.group(3), path.name))
    return found


def zero_return(kind):
    kind = kind.replace("extern", "").replace("static", "").replace("inline", "").strip()
    if kind == "void":
        return ""
    if "*" in kind:
        return "\treturn 0;\n"
    if kind.startswith("struct "):
        return f"\t{kind} zero;\n\n\tmemset(&zero, 0, sizeof(zero));\n\treturn zero;\n"
    return "\treturn 0;\n"


def main():
    log = Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace")
    names = sorted(set(re.findall(r"undefined reference to `([^']+)'", log)))
    old = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    known = set(re.findall(r"^/\* stub: (\w+) ", old, flags=re.M))
    decls = declarations()
    body, missing = [], []
    for name in sorted(set(names) | known):
        if name not in decls:
            missing.append(name)
            continue
        kind, type_, rest, source = decls[name]
        if kind == "function":
            params = rest if rest else "void"
            body.append(f"/* stub: {name} ({source}) */\n__attribute__((weak)) {type_} {name}({params})\n{{\n{zero_return(type_)}}}\n")
        else:
            body.append(f"/* stub: {name} ({source}) */\n__attribute__((weak)) {type_} {name}{rest};\n")
    head = ("/*\nDC_STUBS_GENERATED.C\n\nGenerated by tools/dc_stubs.py - do not edit. Weak placeholders for the\n"
            "n64.h platform API the Dreamcast layer does not implement yet.\n*/\n\n"
            "#include <string.h>\n\n" + "".join(f'#include "{h}"\n' for h in HEADERS) + "\n")
    OUTPUT.write_text(head + "\n".join(body), encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(body)} stubs")
    if missing:
        print("no declaration found for: " + " ".join(missing))


if __name__ == "__main__":
    main()

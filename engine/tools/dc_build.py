#!/usr/bin/env python3
"""Ninja file for the Dreamcast build (port/dc).

    python tools/dc_build.py          # writes build/dc/build.ninja
    ninja -f build/dc/build.ninja     # build/dc/halo.elf (from the repo root)

The game side is the N64 build's (the sources port/n64/port.json selects,
port/n64/game, the XDK layer port/n64/src/xdk_*.c), compiled with
KallistiOS's SH-4 GCC; the platform layer is port/dc/src. Ninja runs the
compiler directly (no shell), so the build works from a Windows prompt.
"""

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from tools.ninja_syntax import Writer  # noqa: E402

N64_DIR = Path("port/n64")
PORT_DIR = Path("port/dc")
BUILD_DIR = Path("build/dc")
XDK_INCLUDE = Path("port/include/xdk")

DC_TOOLCHAINS = Path(os.environ.get("DC_TOOLCHAINS", "C:/DreamSDK/opt/toolchains/dc"))
KOS_BASE = DC_TOOLCHAINS / "kos"
EXE = ".exe" if sys.platform == "win32" else ""


def posix(value):
    return str(value).replace("\\", "/")


# the SH-4 ABI KallistiOS is built with (environ_dreamcast.sh): little-endian,
# single-precision FPU mode, soft atomics
SH4_ABI = [
    "-ml", "-m4-single", "-fomit-frame-pointer",
    "-matomic-model=soft-imask", "-ftls-model=local-exec",
    "-ffunction-sections", "-fdata-sections", "-g",
]

# the MSVC/Xbox environment of the game (tools/n64_build.py GAME_ABI less
# the MIPS options)
GAME_ABI = [
    *SH4_ABI,
    "-fms-extensions",
    "-fshort-wchar",
    "-fcommon",
    "-fno-strict-aliasing",
    "-fwrapv",
    "-fno-delete-null-pointer-checks",
    "-freg-struct-return",
    "-ffp-contract=off",
    "-fno-math-errno",
    "-fsigned-char",
    *(f"-fno-builtin-{name}" for name in (
        "wcslen", "wcsnlen", "wcschr", "wcsrchr", "wcscmp", "wcsncmp", "wcscpy",
        "wcsncpy", "wcscat", "wcsncat", "wmemchr", "wmemcmp", "wmemcpy",
        "wmemmove", "wmemset",
    )),
]

GAME_FLAGS = [
    "-std=gnu89",
    "-D__STRICT_ANSI__",
    "-w",
    "-Wno-error=incompatible-pointer-types",
    "-Wno-error=int-conversion",
    "-Wno-error=implicit-function-declaration",
    "-Wno-error=implicit-int",
    "-Wno-error=return-type",
]

KOS_INCLUDES = [
    f"-I{posix(KOS_BASE / 'include')}",
    f"-I{posix(KOS_BASE / 'kernel/arch/dreamcast/include')}",
    f"-I{posix(KOS_BASE / 'addons/include')}",
]

# KallistiOS's own flags (KOS_CFLAGS), for the platform layer
PLATFORM_FLAGS = [
    *SH4_ABI, "-fno-builtin", "-mfsrra", "-mfsca",
    "-D__DREAMCAST__", "-D_arch_dreamcast", "-D_arch_sub_pristine",
    *KOS_INCLUDES,
    "-std=gnu17", "-Wall", "-Wno-unused-function", "-Wno-unused-variable",
]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--opt", default="-O2", help="optimisation of every unit (default -O2)")
    parser.add_argument("--campaign", action="store_true",
                        help="the campaign disc's build (HALO_N64_CAMPAIGN, the N64 campaign cartridge's game: "
                        "build/dc-campaign)")
    args = parser.parse_args(argv)
    global BUILD_DIR
    if args.campaign:
        BUILD_DIR = Path("build/dc-campaign")
    os.chdir(ROOT)

    port = json.load(open(N64_DIR / "port.json", encoding="utf-8"))
    dc_port = json.load(open(PORT_DIR / "port.json", encoding="utf-8"))
    config = json.load(open(ROOT / "config" / "config.json", encoding="utf-8"))
    project = {p["name"]: p for p in config["projects"]}["halobetacache"]
    options = project.get("options", {})
    exclude_dirs = [d.rstrip("/") + "/" for d in port.get("exclude_dirs", [])]
    exclude_sources = set(port.get("exclude_sources", [])) | set(dc_port.get("exclude_sources", []))
    # (sources the N64 leaves out that the Dreamcast keeps: port/dc/port.json
    # "include_sources")
    included = set(dc_port.get("include_sources", []))
    exclude_sources -= included
    excluded_game = set(dc_port.get("exclude_game_glue", []))

    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    out = open(BUILD_DIR / "build.ninja", "w", encoding="utf-8")
    n = Writer(out)
    n.comment("generated by tools/dc_build.py - do not edit")
    n.variable("builddir", posix(BUILD_DIR))
    n.variable("cc", posix(DC_TOOLCHAINS / "sh-elf" / "bin" / f"sh-elf-gcc{EXE}"))
    n.variable("python", posix(sys.executable))
    n.newline()

    n.rule("cc", command="$cc -MMD -MF $out.d $cflags -c $in -o $out",
           description="DC CC $in", depfile="$out.d", deps="gcc")
    # (a unit's every definition made weak: port/dc/port.json "weaken_sources",
    # placeholders the real code replaces where the Dreamcast compiles it)
    n.variable("objcopy", posix(DC_TOOLCHAINS / "sh-elf" / "bin" / f"sh-elf-objcopy{EXE}"))
    n.rule("weaken", command="$objcopy --weaken $in $out", description="DC WEAKEN $out")
    n.rule("semantics", command="$python tools/linux_msvc_semantics.py --output $out $scan",
           description="DC MSVC SEMANTICS $out", restat=True)
    n.rule("link",
           command=("$cc -ml -m4-single -g -Wl,--gc-sections "
                    f"-T{posix(KOS_BASE / 'utils/ldscripts/shlelf.xc')} -nodefaultlibs "
                    f"-L{posix(KOS_BASE / 'lib/dreamcast')} -L{posix(KOS_BASE / 'addons/lib/dreamcast')} "
                    "-o $out @$out.rsp -Wl,--start-group -lkallisti -lm -lc -lgcc -Wl,--end-group "
                    "-Wl,-Map=$out.map"),
           description="DC LINK $out", rspfile="$out.rsp", rspfile_content="$in_newline")
    n.newline()

    semantics = BUILD_DIR / "halo_msvc_semantics.h"
    game_headers = sorted(posix(p) for p in Path("source").rglob("*") if p.suffix in (".c", ".h"))
    n.build(posix(semantics), "semantics",
            implicit=["tools/linux_msvc_semantics.py", *map(posix, sorted(XDK_INCLUDE.glob("*.h"))), *game_headers],
            variables={"scan": f"--all-inlines --exclude-static --tags source --inlines source --inlines {XDK_INCLUDE.as_posix()}"})

    defines = " ".join(f"-D{d}" for d in options.get("defines") or [] if d not in port.get("drop_defines", []))
    defines += " " + " ".join(f"-D{d}" for d in port.get("defines", []))
    defines += " " + " ".join(f"-D{d}" for d in dc_port.get("defines", []))
    if args.campaign:
        defines += " -DHALO_N64_CAMPAIGN"
    includes = " ".join(
        f"-I\"{d}\"" if " " in d else f"-I{d}"
        for d in options.get("include_dirs") or [] if Path(d) != Path("xbox/include"))
    source_flags = {**port.get("source_flags", {}), **dc_port.get("source_flags", {})}
    weaken_sources = set(dc_port.get("weaken_sources", []))

    objects = []

    def add(source, cflags):
        name = posix(source)
        extra = source_flags.get(name)
        if extra:
            cflags = f"{cflags} {extra}"
        obj = BUILD_DIR / "obj" / Path(source).with_suffix(".o")
        objects.append(posix(obj))
        if name in weaken_sources:
            strong = obj.with_suffix(".strong.o")
            n.build(posix(strong), "cc", name, implicit=[posix(semantics)], variables={"cflags": cflags})
            n.build(posix(obj), "weaken", posix(strong))
            return
        n.build(posix(obj), "cc", name, implicit=[posix(semantics)],
                variables={"cflags": cflags})

    musl = Path("port/third_party/musl-math")
    musl_cflags = " ".join([*GAME_ABI, "-O2", "-std=gnu11", "-w", f"-I{musl.as_posix()}/include",
                            f"-include {musl.as_posix()}/include/libm.h"])
    for source in sorted((musl / "src").glob("*.c")):
        add(source, musl_cflags)

    game_cflags = " ".join([
        *GAME_ABI, args.opt, *GAME_FLAGS,
        f"-I{PORT_DIR.as_posix()}/include", f"-I{N64_DIR.as_posix()}/include", "-Iport/linux/include", "-Iport/include",
        f"-include {PORT_DIR.as_posix()}/include/halo_dc_prefix.h",
        f"-include {posix(semantics)}",
        defines, includes,
        f"-idirafter {XDK_INCLUDE.as_posix()}",
    ])
    game_count = 0
    for o in project["objects"]:
        name = o["name"].replace(os.sep, "/")
        if o["status"] == "MISSING" or not name.endswith(".c") or not Path(name).is_file():
            continue
        if name in exclude_sources or (any(name.startswith(d) for d in exclude_dirs) and name not in included):
            continue
        add(name, game_cflags)
        game_count += 1
    for source in sorted((N64_DIR / "game").glob("*.c")):
        if source.name in excluded_game:
            continue
        extra_flags = " -std=gnu99" if source.name in {"n64_golden.c", "n64_modifiers.c", "n64_render_game.c"} else ""
        add(source, game_cflags + extra_flags)
    for extra in port.get("extra_game_sources", []):
        add(extra, game_cflags)
    # the Dreamcast's own units that see the game's headers (port/dc/game)
    for source in sorted((PORT_DIR / "game").glob("*.c")):
        add(source, game_cflags)

    xdk_cflags = " ".join([
        *(["-DHALO_N64_CAMPAIGN"] if args.campaign else []),
        *GAME_ABI, args.opt,
        "-std=gnu11", "-w", "-DHALO_LINUX_PLATFORM_LAYER",
        f"-I{N64_DIR.as_posix()}/src", f"-I{PORT_DIR.as_posix()}/include", f"-I{N64_DIR.as_posix()}/include",
        "-Iport/linux/src", "-Iport/linux/include", "-Iport/include", "-Isource", "-Isource/cseries",
        f"-include {PORT_DIR.as_posix()}/include/halo_dc_prefix.h",
        f"-include {posix(semantics)}",
        f"-idirafter {XDK_INCLUDE.as_posix()}",
    ])
    for source in sorted((N64_DIR / "src").glob("xdk_*.c")):
        add(source, xdk_cflags)
    # (the Dreamcast's own XDK calls: port/dc/xdk)
    for source in sorted((PORT_DIR / "xdk").glob("*.c")):
        add(source, xdk_cflags)
    for name in port.get("linux_platform_sources", []):
        add(Path("port/linux/src") / name, xdk_cflags)

    platform_cflags = " ".join([args.opt, *PLATFORM_FLAGS, *(["-DHALO_N64_CAMPAIGN"] if args.campaign else []),
                                f"-I{PORT_DIR.as_posix()}/src", f"-I{N64_DIR.as_posix()}/src",
                                f"-I{PORT_DIR.as_posix()}/include"])
    for source in sorted((PORT_DIR / "src").glob("*.c")):
        add(source, platform_cflags)

    elf = BUILD_DIR / "halo.elf"
    n.build(posix(elf), "link", objects,
            implicit=[posix(KOS_BASE / "lib/dreamcast/libkallisti.a")])
    n.build("objects", "phony", objects)
    n.default(posix(elf))
    out.close()
    print(f"{BUILD_DIR / 'build.ninja'}: {game_count} game units, {len(objects)} objects")


if __name__ == "__main__":
    main()
